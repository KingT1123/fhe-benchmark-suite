#!/usr/bin/env python3
"""LaTeX tables and numbers of the energy/memory campaign note
(docs/comparability/energy_campaign_note.tex inputs them; nothing is typed by
hand). Computes no statistics: it only formats aggregate.py's outputs
(--scenario=energy_campaign) and reads session times from the raw data.

Usage (from experiments/openfhe/):
  python3 make_energy_campaign_tables.py
Inputs:  ../results/final/energy_campaign_{sessions,cells,invocations,comparisons,
         comparisons_summary,across_sessions,window_decision}.csv;
         ../results/raw/energy_campaign/<session>/{cell_times,set_aside}.csv
Outputs: energy_campaign_tables/*.tex
"""
import csv
import os
import statistics

OUT = "energy_campaign_tables"
FINAL = "../results/final/energy_campaign"
RAW = "../results/raw/energy_campaign"
SESSIONS = ("day1", "day2")
KEY = {"day1": "One", "day2": "Two"}
OPNAME = {"keygen": "key generation", "decrypt": "decryption", "multiply": "multiplication",
          "relinearize": "relinearization"}


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% GENERATED by experiments/openfhe/make_energy_campaign_tables.py -- do not edit by hand.\n")
        fh.write("\n".join(lines) + "\n")


def load(suffix):
    return list(csv.DictReader(open(f"{FINAL}_{suffix}.csv")))


def mj(x):
    v = 1000 * float(x)
    return f"{v:#.3g}" if v < 100 else f"{v:.0f}"


def f(x, d=2):
    return f"{float(x):.{d}f}"


def main():
    sess = {s["session"]: s for s in load("sessions")}
    cells = load("cells")
    inv = load("invocations")
    comps = load("comparisons")
    summ = {(r["session"], r["quantity"]): r for r in load("comparisons_summary")}
    across = load("across_sessions")
    dec = load("window_decision")
    m = {}

    # ---- sessions
    t = [r"\begin{tabular}{@{}lllrrrrrrr@{}}", r"\toprule",
         r" & & & \multicolumn{2}{c}{Valid invocations} & Idle & Flagged & Pairs & \multicolumn{2}{c}{Set aside} \\",
         r"\cmidrule(lr){4-5}\cmidrule(lr){9-10}",
         r"Session & First start & Last end & energy & memory & W & inv. & $>$10\% & mains & disturb. \\", r"\midrule"]
    for s in SESSIONS:
        ct = [r for r in csv.DictReader(open(os.path.join(RAW, s, "cell_times.csv"))) if r["exit_code"] == "0"]
        first = min(r["start"] for r in ct)
        last = max(r["end"] for r in ct)
        plan = list(csv.DictReader(open(os.path.join(RAW, s, "plan.csv"))))
        ne = sum(int(p["energy_runs"]) for p in plan)
        nm = sum(int(p["memory_runs"]) for p in plan)
        nev = sum(r["session"] == s for r in inv)
        nmv = int(sess[s]["invocations_valid"]) - nev
        S = sess[s]
        t.append(f"{s} & {first[5:10]} {first[11:16]} & {last[5:10]} {last[11:16]} & {nev}/{ne} & {nmv}/{nm} & "
                 f"{f(S['idle_baseline_w_session_median'])} & {S['energy_invocations_flagged']} & "
                 f"{S['cells_pair_disagreement']}/{len(plan)} & {S['set_aside_mains_lost']} & "
                 f"{S['set_aside_recorded_disturbance']} \\\\")
        k = KEY[s]
        m["nEnergy" + k], m["nMem" + k] = f"{nev}/{ne}", f"{nmv}/{nm}"
        m["boostOn" + k] = S["samples_boost_on"]
        m["flagged" + k] = S["energy_invocations_flagged"]
        m["pairs" + k] = S["cells_pair_disagreement"]
        m["cells" + k] = str(len(plan))
        m["base" + k] = f(S["idle_baseline_w_session_median"])
        m["asideMains" + k] = S["set_aside_mains_lost"]
        m["asideDist" + k] = S["set_aside_recorded_disturbance"]
        fq = [float(x["effective_freq_mhz_max"]) for x in inv if x["session"] == s and x["effective_freq_mhz_max"]]
        m["freqMax" + k] = f"{max(fq):.0f}"
    t += [r"\bottomrule", r"\end{tabular}"]
    write("sessions.tex", t)

    # ---- day2 / day1, every cell
    g = [float(a["gross_day2_over_day1"]) for a in across]
    r = [float(a["peak_rss_day2_over_day1"]) for a in across]
    m["acrossN"] = str(len(g))
    m["acrossMedian"] = f(statistics.median(g), 3)
    m["acrossFive"] = str(sum(abs(x - 1) <= 0.05 for x in g))
    m["acrossTen"] = str(sum(abs(x - 1) <= 0.10 for x in g))
    m["acrossMin"], m["acrossMax"] = f(min(g)), f(max(g))
    m["rssAcrossMaxPct"] = f"{100 * max(abs(x - 1) for x in r):.1f}"

    # ---- stage-1 sessions: valid energy / memory invocations against the plan
    for s, k in (("w1", "W"), ("c1", "C")):
        plan = list(csv.DictReader(open(os.path.join(RAW, s, "plan.csv"))))
        nev = sum(r["session"] == s for r in inv)
        m["nEnergy" + k] = f"{nev}/{sum(int(p['energy_runs']) for p in plan)}"
        m["nMem" + k] = f"{int(sess[s]['invocations_valid']) - nev}/{sum(int(p['memory_runs']) for p in plan)}"
        m["cells" + k] = str(len(plan))
    # ---- day2 flagged invocations started between 06:00 and 07:00 on 17 November
    st2 = {r["tag"]: r["start"] for r in csv.DictReader(open(os.path.join(RAW, "day2", "cell_times.csv")))
           if r["exit_code"] == "0"}
    m["flaggedMorningTwo"] = str(sum(
        st2.get(f"{x['library']}_{x['scheme'].lower()}_N{x['N']}_cat{x['category']}_{x['operation']}_energy{x['invocation']}",
                "")[:13] == "2026-11-17T06" for x in inv if x["session"] == "day2" and x["flags"]))

    # ---- window test
    for d in dec:
        m["keygenReps"] = d["keygen_repetitions"]
        m["winDevPct"] = f"{100 * float(d['largest_abs_deviation_20ms_vs_50ms']):.1f}"
        m["winCPct"] = f"{100 * float(d['largest_abs_c_over_openfhe_keygen_block']):.1f}"
        m["winRsdPct"] = f"{100 * float(d['largest_rel_std_openfhe_keygen_run']):.1f}"
        m["winCiPct"] = f"{100 * float(d['ci95_half_width_rel_at_that_count']):.1f}"

    # ---- comparisons: ratio cells
    rc = {(c["session"], c["scheme"], c["N"], c["category"], c["operation"]): c for c in comps
          if c.get("ratio_gross")}
    order = {"keygen": 0, "decrypt": 1, "multiply": 2, "relinearize": 3}
    keys = sorted({k[1:] for k in rc}, key=lambda k: (order[k[3]], k[0], int(k[1]), int(k[2])))
    t = [r"\begin{tabular}{@{}llrrrrrrrr@{}}", r"\toprule",
         r" & & \multicolumn{2}{c}{mJ/op, day1} & \multicolumn{3}{c}{Energy ratio OpenFHE/SEAL} & "
         r"\multicolumn{2}{c}{Peak RSS, MB} & RSS \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}\cmidrule(lr){8-9}",
         r"Operation & Configuration & SEAL & OpenFHE & day1 & day2 & day2$^\circ$ & SEAL & OpenFHE & ratio \\",
         r"\midrule"]
    prev = None
    for k in keys:
        a, b = rc[("day1",) + k], rc[("day2",) + k]
        sch, N, cat, op = k
        if prev and prev != op:
            t.append(r"\addlinespace")
        prev = op
        dag = r"$^\dagger$" if op == "keygen" and int(a["openfhe_inner_loop"]) > 1 else ""
        t.append(f"{OPNAME[op]}{dag} & {sch} {N}/{cat} & {mj(a['seal_gross_j'])} & {mj(a['openfhe_gross_j'])} & "
                 f"{f(a['ratio_gross'])} & {f(b['ratio_gross'])} & {f(b['ratio_gross_without_flagged'])} & "
                 f"{f(a['seal_peak_rss_mb'], 1)} & {f(a['openfhe_peak_rss_mb'], 1)} & {f(a['ratio_peak_rss'])} \\\\")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("compare.tex", t)
    m["nRatioCells"] = str(len(keys))
    for s in SESSIONS:
        k = KEY[s]
        q = summ[(s, "ratio_gross")]
        m["ratioMedian" + k], m["ratioMin" + k], m["ratioMax" + k] = f(q["median"]), f(q["min"]), f(q["max"])
        m["ratioLower" + k] = q["cells_openfhe_lower"]
        q = summ[(s, "ratio_net")]
        m["netMedian" + k] = f(q["median"])
        q = summ[(s, "ratio_peak_rss")]
        m["rssLower" + k] = q["cells_openfhe_lower"]
    # per-operation ranges over both sessions
    for op, name in (("decrypt", "Dec"), ("multiply", "Mul"), ("relinearize", "Relin"), ("keygen", "Kg")):
        v = [float(rc[(s,) + k]["ratio_gross"]) for s in SESSIONS for k in keys if k[3] == op]
        m["r%sMin" % name], m["r%sMax" % name] = f(min(v)), f(max(v))
    dv = [float(rc[(s,) + k]["ratio_gross"]) for s in SESSIONS for k in keys if k[3] == "decrypt" and k[0] != "BGV"]
    m["rDecNoBgvMin"], m["rDecNoBgvMax"] = f(min(dv)), f(max(dv))
    bgv = [float(rc[(s,) + k]["ratio_gross"]) for s in SESSIONS for k in keys if k[0] == "BGV"]
    m["rBgvMin"], m["rBgvMax"] = f(min(bgv)), f(max(bgv))
    rp = [float(rc[(s,) + k]["ratio_peak_rss"]) for s in SESSIONS for k in keys]
    m["rssRatioMin"], m["rssRatioMax"] = f(min(rp)), f(max(rp))
    # the relinearization cell with a disturbed SEAL invocation in day2
    k = ("CKKS", "16384", "1", "relinearize")
    if ("day2",) + k in rc:
        m["relinBigOne"] = f(rc[("day1",) + k]["ratio_gross"])
        m["relinBigTwo"] = f(rc[("day2",) + k]["ratio_gross"])
        m["relinBigTwoClean"] = f(rc[("day2",) + k]["ratio_gross_without_flagged"])
    # package power of key generation (both sessions), to explain energy vs time
    for lib, L in (("seal", "Seal"), ("openfhe", "Ofhe")):
        p = [float(x["package_power_w"]) for x in inv if x["session"] in SESSIONS and x["library"] == lib
             and x["operation"] == "keygen" and not x["flags"]]
        m["kgPow" + L] = f(statistics.median(p), 1)
        p = [float(x["package_power_w"]) for x in inv if x["session"] in SESSIONS and x["library"] == lib
             and x["operation"] != "keygen" and not x["flags"]]
        m["opPow" + L] = f(statistics.median(p), 1)

    # energy ratio (day1) against the latency ratio of the Standard campaign
    # (boost on; openfhe_standard_comparisons.csv), same cells
    lat = {(c["scheme"], c["N"], c["category"], c["operation"]): float(c["ratio_openfhe_over_seal"])
           for c in csv.DictReader(open("../results/final/openfhe_standard_comparisons.csv"))
           if c["ratio_openfhe_over_seal"]}
    dev = [float(rc[("day1",) + k]["ratio_gross"]) / lat[k] - 1 for k in keys if k[3] != "keygen" and k in lat]
    m["latDevMaxPct"] = f"{100 * max(abs(x) for x in dev):.0f}"
    m["latDevN"] = str(len(dev))
    for k, name in ((("CKKS", "16384", "1", "keygen"), "Big"), (("CKKS", "8192", "1", "keygen"), "Mid"),
                    (("CKKS", "2048", "5", "keygen"), "Small")):
        m["kgLat" + name] = f(lat[k])
        m["kgEn" + name] = f(rc[("day1",) + k]["ratio_gross"])

    write("numbers.tex", [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())])
    print(f"wrote {OUT}/: sessions, compare, numbers ({len(m)} macros)")


if __name__ == "__main__":
    main()
