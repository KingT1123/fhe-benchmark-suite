#!/usr/bin/env python3
"""LaTeX tables and numbers of the energy/memory validation account
(docs/comparability/energy_validation_note.tex inputs them; nothing is typed
by hand). Computes no statistics: it only formats aggregate.py's outputs
(--scenario=energy_validation) and reads invocation start times from the raw
data.

Usage (from experiments/openfhe/):
  python3 make_energy_validation_tables.py
Inputs:  ../results/final/energy_validation_{fixed_freq,sessions,cells,invocations,
         across_sessions}.csv; ../results/raw/energy_validation/e*/cell_times.csv
Outputs: energy_validation_tables/*.tex
"""
import csv
import os

OUT = "energy_validation_tables"
FINAL = "../results/final/energy_validation"
RAW = "../results/raw/energy_validation"
SCHEMES = ("BFV", "BGV", "CKKS")
OPS = ("keygen", "encrypt", "multiply", "relinearize")
LIBS = (("seal", "SEAL"), ("openfhe", "OpenFHE"))
HIGH_IDLE = 1.15   # an idle reading above 1.15 x its session's median is listed as high


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% GENERATED by experiments/openfhe/make_energy_validation_tables.py -- do not edit by hand.\n")
        f.write("\n".join(lines) + "\n")


def load(suffix):
    return list(csv.DictReader(open(f"{FINAL}_{suffix}.csv")))


def f(x, d=2):
    return f"{float(x):.{d}f}"


def pct(x):
    return f"{100 * float(x):+.0f}\\%"


def main():
    fixed, sess, cells, inv, across = (load(s) for s in ("fixed_freq", "sessions", "cells", "invocations", "across_sessions"))
    sessions = [s["session"] for s in sess]
    cell = {(c["session"], c["library"], c["scheme"], c["operation"]): c for c in cells}
    invk = {(i["session"], i["library"], i["scheme"], i["operation"], i["invocation"]): i for i in inv}
    acr = {(a["library"], a["scheme"], a["operation"]): a for a in across}
    starts, m = {}, {}
    for s in sessions:
        ct = list(csv.DictReader(open(os.path.join(RAW, s, "cell_times.csv"))))
        for r in ct:
            if r["exit_code"] == "0":
                starts[(s, r["tag"])] = r["start"][11:19]
        k = s.replace("e1", "One").replace("e2", "Two")
        m["date" + k], m["first" + k], m["last" + k] = ct[0]["start"][:10], ct[0]["start"][11:16], ct[-1]["end"][11:16]

    # ---- part A
    names = {"boost_on_mains": "Boost on, mains (reference)", "fixed_mains": "Boost off, mains",
             "fixed_battery": "Boost off, battery"}
    t = [r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
         r"Phase & s & Freq.\ median, MHz & Min--max, MHz & Temp.\ median, \textdegree C & Package, W \\", r"\midrule"]
    for r in fixed:
        t.append(f"{names[r['phase']]} & {r['seconds']} & {float(r['effective_freq_mhz_median']):.0f} & "
                 f"{float(r['effective_freq_mhz_min']):.0f}--{float(r['effective_freq_mhz_max']):.0f} & "
                 f"{f(r['temp_c_median'], 1)} & {f(r['package_power_w_median'], 1)} \\\\")
        k = {"boost_on_mains": "On", "fixed_mains": "Mains", "fixed_battery": "Battery"}[r["phase"]]
        m["freqA" + k] = f"{float(r['effective_freq_mhz_median']):.0f}"
        m["powA" + k] = f(r["package_power_w_median"], 1)
        m["tempA" + k] = f(r["temp_c_median"], 0)
        m["lowA" + k] = r["samples_below_3200_mhz"]
    t += [r"\bottomrule", r"\end{tabular}"]
    write("fixed_freq.tex", t)
    m["powDropA"] = f"{100 * (1 - float(m['powABattery']) / float(m['powAMains'])):.0f}"

    # ---- sessions
    t = [r"\begin{tabular}{@{}lrrrrrrrr@{}}", r"\toprule",
         r"Session & Valid & Set aside & Boost on & Off mains & Freq., MHz & Temp., \textdegree C & Idle readings, W & Idle windows, W \\",
         r" & & & samples & samples & median & median (max) & median (min--max) & start / end \\", r"\midrule"]
    for s in sess:
        t.append(f"{s['session']} & {s['invocations_valid']} & {s['set_aside_mains_lost']} & {s['samples_boost_on']} & "
                 f"{s['samples_off_mains']} & {float(s['effective_freq_mhz_median']):.0f} & "
                 f"{f(s['temp_c_median'], 0)} ({f(s['temp_c_max'], 0)}) & "
                 f"{f(s['idle_baseline_w_session_median'])} ({f(s['idle_reading_w_min'])}--{f(s['idle_reading_w_max'])}) & "
                 f"{f(s['idle_start_window_w'])} / {f(s['idle_end_window_w'])} \\\\")
        k = s["session"].replace("e1", "One").replace("e2", "Two")
        m["base" + k] = f(s["idle_baseline_w_session_median"])
        m["idleMin" + k], m["idleMax" + k] = f(s["idle_reading_w_min"]), f(s["idle_reading_w_max"])
        m["idleStart" + k], m["idleEnd" + k] = f(s["idle_start_window_w"]), f(s["idle_end_window_w"])
        m["temp" + k], m["tempMax" + k] = f(s["temp_c_median"], 0), f(s["temp_c_max"], 0)
    t += [r"\bottomrule", r"\end{tabular}"]
    write("sessions.tex", t)
    m["nInvPerSession"] = sess[0]["invocations_valid"]
    m["nSetAside"] = str(sum(int(s["set_aside_mains_lost"]) for s in sess))
    m["nBoostOn"] = str(sum(int(s["samples_boost_on"]) for s in sess))
    m["nOffMains"] = str(sum(int(s["samples_off_mains"]) for s in sess))
    fr = [float(i["effective_freq_mhz_median"]) for i in inv if i["effective_freq_mhz_median"]]
    m["freqInvMin"], m["freqInvMax"] = f"{min(fr):.0f}", f"{max(fr):.0f}"

    # ---- gross energy (primary)
    t = [r"\begin{tabular}{@{}llrrrrrrr@{}}", r"\toprule",
         r" & & Inner & Window & \multicolumn{2}{c}{e1} & \multicolumn{2}{c}{e2} & \\",
         r"\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
         r"Library & Cell & loop & ms & mJ/op & inv.\,2/1 & mJ/op & inv.\,2/1 & e2/e1 \\", r"\midrule"]
    noteq, within5, gr = [], 0, []
    for lib, name in LIBS:
        for sch in SCHEMES:
            for op in OPS:
                row = [name, f"{sch} {op}", cell[(sessions[0], lib, sch, op)]["inner_loop"]]
                win = [float(invk[(s, lib, sch, op, k)]["window_ms_mean"]) for s in sessions for k in ("1", "2")]
                row.append(f"{sum(win) / len(win):.0f}")
                for s in sessions:
                    c = cell[(s, lib, sch, op)]
                    mark = "" if c["gross_tost_10pct"] == "equivalent_within_margin" else "$^*$"
                    if mark:
                        noteq.append((s, lib, sch, op, c))
                    gr.append(float(c["gross_ratio_inv2_inv1"]))
                    row += [f"{1000 * float(c['gross_j_mean']):.4g}", f(c["gross_ratio_inv2_inv1"]) + mark]
                a = float(acr[(lib, sch, op)]["gross_ratio_s2_s1"])
                within5 += abs(a - 1) <= 0.05
                row.append(f(a))
                t.append(" & ".join(row) + r" \\")
        if lib == "seal":
            t.append(r"\midrule")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("gross.tex", t)
    m["nCellsSess"] = str(len(cells))
    m["nEquiv"] = str(len(cells) - len(noteq))
    m["nNotEquiv"] = str(len(noteq))
    m["nAcross"], m["nAcrossFive"] = str(len(across)), str(within5)
    m["nRatioFive"] = str(sum(abs(x - 1) <= 0.05 for x in gr))
    ar = [float(a["gross_ratio_s2_s1"]) for a in across]
    m["acrossMin"], m["acrossMax"] = f(min(ar)), f(max(ar))

    # ---- cells where equivalence was not established
    t = [r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
         r"Session & Cell & inv.\,2/1 & Window & Start time & Idle reading, W & Rel.\ std \\",
         r" & & & ms & inv.\,1 / inv.\,2 & inv.\,1 / inv.\,2 & inv.\,1 / inv.\,2 \\",
         r"\midrule"]
    for s, lib, sch, op, c in sorted(noteq, key=lambda x: x[0]):
        i1, i2 = invk[(s, lib, sch, op, "1")], invk[(s, lib, sch, op, "2")]
        tag = f"{lib}_{sch.lower()}_N8192_cat1_{op}_energy"
        rs = [100 * float(i["gross_std"]) / float(i["gross_j_per_op"]) for i in (i1, i2)]
        t.append(f"{s} & {dict(LIBS)[lib]} {sch} {op} & {f(c['gross_ratio_inv2_inv1'])} & "
                 f"{(float(i1['window_ms_mean']) + float(i2['window_ms_mean'])) / 2:.0f} & "
                 f"{starts[(s, tag + '1')]} / {starts[(s, tag + '2')]} & "
                 f"{f(i1['idle_reading_w'])} / {f(i2['idle_reading_w'])} & {rs[0]:.0f}\\% / {rs[1]:.0f}\\% \\\\")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("not_equivalent.tex", t)
    m["nRatioTen"] = str(sum(abs(x - 1) <= 0.10 for x in gr))

    # ---- high idle readings
    high = []
    for s in sess:
        b = float(s["idle_baseline_w_session_median"])
        for i in inv:
            if i["session"] == s["session"] and float(i["idle_reading_w"]) > HIGH_IDLE * b:
                tag = f"{i['library']}_{i['scheme'].lower()}_N8192_cat1_{i['operation']}_energy{i['invocation']}"
                high.append((s["session"], starts[(s["session"], tag)], i))
    high.sort(key=lambda x: (x[0], x[1]))
    m["highFactor"] = f"{HIGH_IDLE:.2f}"
    for s in sessions:
        k = s.replace("e1", "One").replace("e2", "Two")
        h = [x for x in high if x[0] == s]
        m["nHigh" + k] = str(len(h))
        m["highTimes" + k] = ", ".join(x[1][:5] for x in h) if h else "none"

    # ---- idle-corrected energy (complementary) and memory
    t = [r"\begin{tabular}{@{}llrrrrrrr@{}}", r"\toprule",
         r" & & \multicolumn{2}{c}{Net, mJ/op} & Net/gross & \multicolumn{2}{c}{e2: baseline sensitivity} & \multicolumn{2}{c}{Peak RSS, MB} \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
         r"Library & Cell & e1 & e2 & e2 & lowest & highest & e1 & e2 \\", r"\midrule"]
    share, sens, rss, rng = [], [], [], []
    for lib, name in LIBS:
        for sch in SCHEMES:
            for op in OPS:
                c1, c2 = cell[(sessions[0], lib, sch, op)], cell[(sessions[1], lib, sch, op)]
                share += [float(c1["net_share_of_gross"]), float(c2["net_share_of_gross"])]
                sens += [float(c2["net_rel_change_lowest_reading"]), float(c2["net_rel_change_highest_reading"])]
                rss += [float(c1["peak_rss_mb_mean"]), float(c2["peak_rss_mb_mean"])]
                rng += [float(c["peak_rss_mb_max"]) - float(c["peak_rss_mb_min"]) for c in (c1, c2)]
                t.append(f"{name} & {sch} {op} & {1000 * float(c1['net_j_mean']):.4g} & {1000 * float(c2['net_j_mean']):.4g} & "
                         f"{f(c2['net_share_of_gross'])} & {pct(c2['net_rel_change_lowest_reading'])} & "
                         f"{pct(c2['net_rel_change_highest_reading'])} & {f(c1['peak_rss_mb_mean'], 1)} & "
                         f"{f(c2['peak_rss_mb_mean'], 1)} \\\\")
        if lib == "seal":
            t.append(r"\midrule")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("net_memory.tex", t)
    m["shareMin"], m["shareMax"] = f"{100 * min(share):.0f}", f"{100 * max(share):.0f}"
    m["sensMinTwo"] = f"{100 * min(abs(x) for x in sens):.0f}"
    m["sensMaxTwo"] = f"{100 * max(abs(x) for x in sens):.0f}"
    s1 = [float(c[k]) for c in cells if c["session"] == sessions[0]
          for k in ("net_rel_change_lowest_reading", "net_rel_change_highest_reading")]
    m["sensMaxOne"] = f"{100 * max(abs(x) for x in s1):.0f}"
    win = [float(c[k]) for c in cells for k in ("net_rel_change_idle_start_window", "net_rel_change_idle_end_window")
           if c["session"] == sessions[1]]
    m["sensWinMaxTwo"] = f"{100 * max(abs(x) for x in win):.0f}"
    sw1 = [float(c["net_rel_change_idle_start_window"]) for c in cells if c["session"] == sessions[0]]
    m["sensStartMaxOne"] = f"{100 * max(abs(x) for x in sw1):.0f}"
    m["rssMin"], m["rssMax"] = f(min(rss), 1), f(max(rss), 1)
    m["rssRangeMax"] = f(max(rng), 2)
    m["rssAcrossMax"] = f(max(abs(float(cell[(sessions[0], l, s, o)]["peak_rss_mb_mean"])
                                  - float(cell[(sessions[1], l, s, o)]["peak_rss_mb_mean"]))
                              for l, _ in LIBS for s in SCHEMES for o in OPS), 2)
    nr = [float(a["net_ratio_s2_s1"]) for a in across]
    m["netAcrossTen"] = str(sum(abs(x - 1) <= 0.10 for x in nr))
    m["netAcrossMin"], m["netAcrossMax"] = f(min(nr)), f(max(nr))

    write("numbers.tex", [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())])
    print(f"wrote {OUT}/: fixed_freq, sessions, gross, not_equivalent, net_memory, numbers ({len(m)} macros)")


if __name__ == "__main__":
    main()
