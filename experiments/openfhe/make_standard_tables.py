#!/usr/bin/env python3
"""LaTeX tables and numbers of the Standard campaign results note
(docs/comparability/openfhe_standard_results.tex inputs them; nothing is typed
by hand). Computes no statistics: it only formats aggregate.py's outputs
(--scenario=openfhe_standard) and lists the cells set aside in the raw data.

Usage (from experiments/openfhe/):
  python3 make_standard_tables.py
Inputs:  ../results/final/openfhe_standard.csv, _comparisons.csv, _sessions.csv,
         _excluded.csv; ../results/raw/standard_campaign/s*/set_aside_*/,
         s*/cell_times.csv; probe/operations_v2.csv
Outputs: standard_tables/*.tex
"""
import csv
import glob
import os
import statistics

OUT = "standard_tables"
FINAL = "../results/final/openfhe_standard"
RAW = "../results/raw/standard_campaign"
EQUIV = ["keygen", "decrypt", "multiply", "relinearize", "rotate"]
# (session, scheme, N, category, operation) measured again in a later session
# and replaced by it in every summary; still listed, marked, in the tables.
# s5 CKKS 16384/1 relinearization: its two cells ran on different kernels;
# measured again in s6 under one kernel (review of openfhe-standard-v1).
SUPERSEDED = {("s5", "CKKS", "16384", "1", "relinearize"): "s6"}


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% GENERATED by experiments/openfhe/make_standard_tables.py -- do not edit by hand.\n")
        f.write("\n".join(lines) + "\n")


def fmt(x):
    """4 significant digits, no exponent (latencies span 0.008 to 270 ms)."""
    s = f"{float(x):.4g}"
    return f"{float(x):.6f}" if "e" in s else s


def cfg_key(r):
    return (int(r["N"]), int(r["category"]), r["scheme"])


def main():
    rows = list(csv.DictReader(open(FINAL + ".csv")))
    comps = list(csv.DictReader(open(FINAL + "_comparisons.csv")))
    sess = list(csv.DictReader(open(FINAL + "_sessions.csv")))
    excl = list(csv.DictReader(open(FINAL + "_excluded.csv")))
    sup = lambda r: (r["session"], r["scheme"], r["N"], r["category"], r["operation"]) in SUPERSEDED
    cell = {(r["library"], r["scheme"], r["N"], r["category"], r["operation"]): r for r in rows if not sup(r)}
    macros, keyed = {}, []

    # ---- session conditions --------------------------------------------------
    t = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
         r"Session & Configurations & Cells & Valid & Excl. & Freq., MHz & Temp., \textdegree C & SEAL/archived \\",
         r"\midrule"]
    configs = sorted({(r["session"], r["scheme"], r["N"], r["category"]) for r in rows},
                     key=lambda k: (k[0], int(k[2]), int(k[3]), k[1]))
    for s in sess:
        names = ", ".join(f"{sc} {N}/{c}" for ss, sc, N, c in configs if ss == s["session"])
        rr = [float(r["seal_vs_archived_ratio"]) for r in rows if r["session"] == s["session"] and r["seal_vs_archived_ratio"]]
        t.append(f'{s["session"]} & \\parbox[t]{{5.2cm}}{{\\raggedright {names}}} & {s["cells_listed"]} & {s["cells_valid"]} & '
                 f'{s["cells_excluded"]} & {float(s["effective_freq_mhz_median"]):.0f} & {float(s["temp_c_median"]):.1f} & '
                 f'{min(rr):.2f}--{statistics.median(rr):.2f}--{max(rr):.2f} ({len(rr)}) \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write("sessions.tex", t)
    macros.update({"nSessions": len(sess), "nConfigs": len({k[1:] for k in configs}),
                   "nCells": sum(int(s["cells_listed"]) for s in sess),
                   "nValid": sum(int(s["cells_valid"]) for s in sess), "nExcluded": len(excl),
                   "nComparisons": len(comps),
                   "nUsed": sum(1 for r in rows if not sup(r)), "nSuperseded": sum(1 for r in rows if sup(r)),
                   "nRatios": sum(1 for c in comps if c["ratio_openfhe_over_seal"] and not sup(c)),
                   "nHighVar": sum(r["flag"] == "HIGH_VARIANCE" for r in rows)})
    allr = [float(r["seal_vs_archived_ratio"]) for r in rows if r["seal_vs_archived_ratio"]]
    macros.update({"archN": len(allr), "archMedian": f"{statistics.median(allr):.2f}",
                   "archMin": f"{min(allr):.2f}", "archMax": f"{max(allr):.2f}"})

    # ---- matched-profile comparisons: equivalent boundaries, with ratio --------
    t = [r"\begin{tabular}{@{}lllrrrrrr@{}}", r"\toprule",
         r"& & & \multicolumn{2}{c}{mean, ms} & \multicolumn{3}{c}{ratio O/S} & \\",
         r"\cmidrule(lr){4-5}\cmidrule(lr){6-8}",
         r"Sess. & Config. & Operation & SEAL & OpenFHE & means & medians & quartiles & OpenFHE $-$ SEAL, 90\% CI, ms \\",
         r"\midrule"]
    m = sorted((c for c in comps if c["ratio_openfhe_over_seal"]),
               key=lambda c: (EQUIV.index(c["operation"]), int(c["N"]), int(c["category"]), c["scheme"]))
    prev = None
    for c in m:
        if prev and prev != c["operation"]:
            t.append(r"\addlinespace")
        prev = c["operation"]
        name = r"decrypt$^\ast$" if c["operation"] == "decrypt" else c["operation"]
        mark = r"$^\dagger$" if sup(c) else ""
        t.append(f'{c["session"]}{mark} & {c["scheme"]} {c["N"]}/{c["category"]} & {name} & {fmt(c["seal_mean_ms"])} & '
                 f'{fmt(c["openfhe_mean_ms"])} & {float(c["ratio_openfhe_over_seal"]):.2f} & {float(c["ratio_of_medians"]):.2f} & '
                 f'{float(c["ratio_quartile_low"]):.2f}--{float(c["ratio_quartile_high"]):.2f} & '
                 f'[{fmt(c["diff_ci90_low"])}, {fmt(c["diff_ci90_high"])}] \\\\')
        if sup(c):   # kept in the table, out of every summary
            keyed.append((f'old:{c["scheme"]}:{c["N"]}:{c["category"]}:{c["operation"]}', f'{float(c["ratio_openfhe_over_seal"]):.2f}'))
            continue
        keyed.append((f'rm:{c["scheme"]}:{c["N"]}:{c["category"]}:{c["operation"]}', f'{float(c["ratio_of_medians"]):.2f}'))
        keyed.append((f'rq:{c["scheme"]}:{c["N"]}:{c["category"]}:{c["operation"]}',
                      f'{float(c["ratio_quartile_low"]):.2f}--{float(c["ratio_quartile_high"]):.2f}'))
        keyed.append((f'r:{c["scheme"]}:{c["N"]}:{c["category"]}:{c["operation"]}', f'{float(c["ratio_openfhe_over_seal"]):.2f}'))
        keyed.append((f'x:{c["scheme"]}:{c["N"]}:{c["category"]}:{c["operation"]}', f'{1 / float(c["ratio_openfhe_over_seal"]):.1f}'))
    t += [r"\bottomrule", r"\end{tabular}"]
    write("matched.tex", t)
    for op in EQUIV:
        rs = [float(c["ratio_openfhe_over_seal"]) for c in m if c["operation"] == op and not sup(c)]
        if rs:
            macros[f"ratioMin{op}"], macros[f"ratioMax{op}"], macros[f"ratioN{op}"] = f"{min(rs):.2f}", f"{max(rs):.2f}", len(rs)
            macros[f"speedMin{op}"], macros[f"speedMax{op}"] = f"{1 / max(rs):.1f}", f"{1 / min(rs):.1f}"
    m = [c for c in m if not sup(c)]
    ck = [float(c["ratio_openfhe_over_seal"]) for c in m if c["operation"] == "decrypt" and c["scheme"] == "CKKS"]
    macros.update({"ratioMinckksdecrypt": f"{min(ck):.2f}", "ratioMaxckksdecrypt": f"{max(ck):.2f}",
                   "ratioNckksdecrypt": len(ck)})
    macros["nMatchedConfigs"] = len({(c["scheme"], c["N"], c["category"]) for c in comps
                                     if c["comparability_class"] == "matched-profile comparison"})

    dev = [abs(float(c["ratio_of_medians"]) / float(c["ratio_openfhe_over_seal"]) - 1) for c in m]
    macros["medianDevMaxOthers"] = f'{100 * sorted(dev)[-2]:.0f}'   # largest except the rotation, discussed apart

    # ---- reproducibility across independent sessions (CKKS 8192/1) -------------
    rp = list(csv.DictReader(open(FINAL + "_reproducibility.csv")))
    srcs = list(dict.fromkeys(r["source"] for r in rp))
    t = [r"\begin{tabular}{@{}l" + "r" * len(srcs) + "r@{}}", r"\toprule",
         "Operation & " + " & ".join(srcs) + r" & range \\", r"\midrule"]
    for op in EQUIV:
        rr = {r["source"]: r for r in rp if r["operation"] == op}
        if len(rr) < 2:
            continue
        vals = [float(rr[s_]["ratio_of_means"]) for s_ in srcs if s_ in rr]
        meds = [float(rr[s_]["ratio_of_medians"]) for s_ in srcs if s_ in rr]
        t.append(f"{op} & " + " & ".join(f'{float(rr[s_]["ratio_of_means"]):.2f} ({float(rr[s_]["ratio_of_medians"]):.2f})'
                                          if s_ in rr else "--" for s_ in srcs) + f" & {min(vals):.2f}--{max(vals):.2f} \\\\")
        macros[f"repMin{op}"], macros[f"repMax{op}"] = f"{min(vals):.2f}", f"{max(vals):.2f}"
        macros[f"repMedMin{op}"], macros[f"repMedMax{op}"] = f"{min(meds):.2f}", f"{max(meds):.2f}"
    t += [r"\bottomrule", r"\end{tabular}"]
    write("reproducibility.tex", t)
    macros["nRepSessions"] = len(srcs)

    # ---- separate analysis: values per library, NO ratio ----------------------
    t = [r"\begin{tabular}{@{}lllrr@{\hspace{1.2em}}lllrr@{}}", r"\toprule",
         r"Sess. & Config. & Operation & SEAL, ms & OpenFHE, ms & Sess. & Config. & Operation & SEAL, ms & OpenFHE, ms \\",
         r"\midrule"]
    sep = sorted((c for c in comps if c["boundary"] == "equivalent computation" and not c["ratio_openfhe_over_seal"]),
                 key=lambda c: (int(c["N"]), int(c["category"]), c["scheme"], EQUIV.index(c["operation"])))
    half = (len(sep) + 1) // 2
    for i in range(half):
        parts = []
        for c in (sep[i], sep[i + half] if i + half < len(sep) else None):
            parts.append(f'{c["session"]} & {c["scheme"]} {c["N"]}/{c["category"]} & {c["operation"]} & '
                         f'{fmt(c["seal_mean_ms"])} & {fmt(c["openfhe_mean_ms"])}' if c else "& & & &")
        t.append(" & ".join(parts) + r" \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("separate.tex", t)
    macros["nSeparateConfigs"] = len({(c["scheme"], c["N"], c["category"]) for c in comps
                                      if c["comparability_class"] != "matched-profile comparison"})
    macros["nSeparateCells"] = len(sep)

    # ---- end-to-end API costs: each library's own call, NO ratio --------------
    t = [r"\begin{tabular}{@{}llrrrrrrr@{}}", r"\toprule",
         r"& & \multicolumn{2}{c}{encrypt} & \multicolumn{3}{c}{add} & \multicolumn{2}{c}{decrypt} \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}\cmidrule(lr){8-9}",
         r"Sess. & Configuration & SEAL & \texttt{Encrypt} & SEAL & \texttt{EvalAdd} & \texttt{EvalAddInPlace} & SEAL & \texttt{Decrypt} (full) \\",
         r"\midrule"]
    for ss, sc, N, c in sorted(configs, key=lambda k: (int(k[2]), int(k[3]), k[1])):
        g = lambda lib, op: cell.get((lib, sc, N, c, op))
        v = lambda r: fmt(r["mean_ms"]) if r else "--"
        t.append(f'{ss} & {sc} {N}/{c} & {v(g("SEAL", "encrypt"))} & {v(g("OpenFHE", "encrypt"))} & '
                 f'{v(g("SEAL", "add"))} & {v(g("OpenFHE", "add"))} & {v(g("OpenFHE", "add_inplace"))} & '
                 f'{v(g("SEAL", "decrypt"))} & {v(g("OpenFHE", "decrypt_full"))} \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write("api.tex", t)
    for r in rows:  # every mean, for the text: \val{OpenFHE:CKKS:16384:1:add}
        keyed.append((f'v:{r["library"]}:{r["scheme"]}:{r["N"]}:{r["category"]}:{r["operation"]}', fmt(r["mean_ms"])))
    copy = [float(cell[("OpenFHE", s, N, c, "add")]["mean_ms"]) / float(cell[("OpenFHE", s, N, c, "add_inplace")]["mean_ms"])
            for _, s, N, c in configs if ("OpenFHE", s, N, c, "add_inplace") in cell]
    macros.update({"copyMin": f"{min(copy):.1f}", "copyMax": f"{max(copy):.1f}"})

    # ---- problematic cells -----------------------------------------------------
    t = [r"\begin{tabular}{@{}lllrrrl@{}}", r"\toprule",
         r"Session & Library & Cell & mean, ms & median, ms & CV\% & IQR, ms \\", r"\midrule"]
    for r in sorted((r for r in rows if r["flag"] == "HIGH_VARIANCE"), key=lambda r: r["session"]):
        cv = 100 * float(r["std_ms"]) / float(r["mean_ms"])
        t.append(f'{r["session"]} & {r["library"]} & {r["scheme"]} {r["N"]}/{r["category"]} {r["operation"].replace("_", " ")} & '
                 f'{fmt(r["mean_ms"])} & {fmt(r["median_ms"])} & {cv:.1f} & [{fmt(r["iqr_low_ms"])}, {fmt(r["iqr_high_ms"])}] \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write("highvar.tex", t)

    t = [r"\begin{tabular}{@{}llll@{}}", r"\toprule",
         r"Session & Cell set aside & Measured on battery (set aside) & Measured again on mains (kept) \\", r"\midrule"]
    n_aside = 0
    for sd in sorted(glob.glob(os.path.join(RAW, "s*"))):
        windows = {}
        for r in csv.DictReader(open(os.path.join(sd, "cell_times.csv"))):
            windows.setdefault(r["tag"], []).append((r["start"][:16].replace("T", " "), r["end"][11:16]))
        for f in sorted(glob.glob(os.path.join(sd, "set_aside_*", "*.csv"))):
            tag = os.path.basename(f)[:-4]
            w = windows.get(tag, [])
            n_aside += 1
            t.append(f'{os.path.basename(sd)} & {tag.replace("_", r"\_")} & {w[0][0]}--{w[0][1] if w else ""} & '
                     f'{w[-1][0]}--{w[-1][1]} \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write("set_aside.tex", t)
    macros["nSetAside"] = n_aside

    t = [r"\begin{tabular}{@{}llrrrl@{}}", r"\toprule",
         r"Session & Cell & Freq., MHz & Temp., \textdegree C & SEAL/archived & Kernel \\", r"\midrule"]
    for r in rows:
        if r["session"] in ("s4", "s5", "s6"):
            t.append(f'{r["session"]} & {r["library"]} {r["operation"].replace("_", " ")} & {float(r["effective_freq_mhz_mean"]):.0f} & '
                     f'{float(r["temp_c_mean"]):.1f} & {format(float(r["seal_vs_archived_ratio"]), ".3f") if r["seal_vs_archived_ratio"] else "--"} & '
                     f'{r["kernel"].replace("-generic", "")} \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write("conditions_s4s5.tex", t)
    fq = {r["session"]: [] for r in rows}
    for r in rows:
        if r["effective_freq_mhz_mean"] and r["operation"] != "keygen":
            fq[r["session"]].append(float(r["effective_freq_mhz_mean"]))
    for s, v in fq.items():
        macros[f"freqMin{s}"], macros[f"freqMax{s}"] = f"{min(v) / 1000:.2f}", f"{max(v) / 1000:.2f}"

    write("numbers.tex", [f"\\newcommand{{\\{k.replace('s1', 'sone').replace('s2', 'stwo').replace('s3', 'sthree').replace('s4', 'sfour').replace('s5', 'sfive').replace('s6', 'ssix')}}}{{{v}}}"
                          for k, v in macros.items()]
          + [f"\\expandafter\\def\\csname {k}\\endcsname{{{v}}}" for k, v in keyed])
    print("wrote", sorted(os.listdir(OUT)))


if __name__ == "__main__":
    main()
