#!/usr/bin/env python3
"""LaTeX tables and numbers of the OpenFHE pilot note, generated from the data
(docs/comparability/openfhe_pilot_note.tex inputs them; nothing is typed by
hand). Computes no statistics: it only formats aggregate.py's outputs and
the archived estimator / correctness files.

Usage (from experiments/openfhe/):
  python3 make_pilot_tables.py              # the pilot run (results/final/pilot.csv)
  python3 make_pilot_tables.py --run pilot_run1 --prefix run1
Inputs:  ../results/final/<run>.csv, <run>_comparisons.csv
         ../security/results_sensitivity_N8192_cat5.csv, results_sensitivity_seal_N8192_cat5.csv
         correctness/correctness_v2.csv, negative_controls_out.csv
         probe/eligible_v2.csv, probe/security_v2.csv
Outputs: pilot_tables/<prefix>_*.tex and pilot_tables/<prefix>_numbers.tex
         (<prefix> defaults to the run name)
"""
import argparse
import csv
import statistics
import os
from collections import defaultdict

OPS = ["keygen", "encrypt", "decrypt", "add", "multiply", "relinearize", "rotate"]
OUT = "pilot_tables"


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% GENERATED by experiments/openfhe/make_pilot_tables.py -- do not edit by hand.\n")
        f.write("\n".join(lines) + "\n")


def fmt(x, nd=3):
    x = float(x)
    return f"{x:.{nd}f}" if x < 100 else f"{x:.1f}"


def results_tables(run, prefix, macros):
    rows = list(csv.DictReader(open(f"../results/final/{run}.csv")))
    lat = {(r["library"], r["operation"], r["ckks_scale_bits"]): r for r in rows if r["metric"] == "latency_ms"}
    corr = {r["operation"]: r for r in rows if r["metric"] == "correct_repetitions"}
    comps = list(csv.DictReader(open(f"../results/final/{run}_comparisons.csv")))
    cmp = {(c["comparison"], c["operation"]): c for c in comps}

    def cell(r):
        cv = 100 * float(r["std"]) / float(r["mean"])
        flag = r"$^\dagger$" if r["flag"] == "HIGH_VARIANCE" else ""
        return f'{fmt(r["mean"])} [{fmt(r["ci_low"])}, {fmt(r["ci_high"])}] & {cv:.1f}{flag}'

    # (a) equivalent computational boundaries: the same computation is timed
    # in both libraries, so the OpenFHE/SEAL ratio is meaningful
    EQUIV = ["keygen", "decrypt", "multiply", "relinearize", "rotate"]
    t = [r"\begin{tabular}{@{}lrrrrrc@{}}", r"\toprule",
         r"Operation & \multicolumn{2}{c}{SEAL 4.1.2} & \multicolumn{2}{c}{OpenFHE 1.5.1} & Ratio O/S & Correct \\",
         r"& mean [95\% CI], ms & CV\% & mean [95\% CI], ms & CV\% & & \\", r"\midrule"]
    for op in EQUIV:
        s, o, c = lat.get(("SEAL", op, "40")), lat.get(("OpenFHE", op, "40")), cmp.get(("openfhe_vs_seal", op))
        if s and o and c:
            name = "decrypt (SEAL's boundary)" if op == "decrypt" else op
            t.append(f'{name} & {cell(s)} & {cell(o)} & {float(c["ratio"]):.2f} & '
                     f'{corr[op]["mean"]}/{corr[op]["n"]} \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write(f"{prefix}_results.tex", t)

    # (b) end-to-end API costs: each library's own call, which does NOT perform
    # the same computation -- no ratio is formed
    API = [("encrypt", "encrypt", "encrypt", "Encrypt",
            "SEAL also encrypts with its special prime, then removes it"),
           ("add", "add", "add", "EvalAdd", "EvalAdd first copies its operand into a new ciphertext"),
           ("add, in place", None, "add_inplace", "EvalAddInPlace", "no copy; SEAL has no separate call timed"),
           ("decrypt, full API", "decrypt", "decrypt_full", "Decrypt",
            "OpenFHE also inverts the NTT, reconstructs and decodes; SEAL's decrypt stops before")]
    t = [r"\begin{tabular}{@{}llrlrL{5.0cm}@{}}", r"\toprule",
         r"Operation & SEAL call & mean, ms & OpenFHE call & mean, ms & What differs \\", r"\midrule"]
    for name, sop, oop, ocall, why in API:
        s = lat.get(("SEAL", sop, "40")) if sop else None
        o = lat.get(("OpenFHE", oop, "40"))
        if not o:
            continue
        t.append(f'{name} & {"\\texttt{" + sop + "}" if s else "--"} & {fmt(s["mean"]) if s else "--"} & '
                 f'\\texttt{{{ocall}}} & {fmt(o["mean"])} & {why} \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write(f"{prefix}_api.tex", t)

    t = [r"\begin{tabular}{@{}lrrrrl@{}}", r"\toprule",
         r"Operation & $2^{40}$, ms & $2^{30}$, ms & ratio & diff.\ 90\% CI, ms & TOST $\pm$5\% \\", r"\midrule"]
    for op in OPS:
        c = cmp.get(("scale_test", op))
        if c:
            v = "equivalent" if c["verdict"] == "equivalent_within_margin" else "not established"
            t.append(f'{op} & {fmt(c["ref_mean_ms"])} & {fmt(c["new_mean_ms"])} & {float(c["ratio"]):.3f} & '
                     f'[{float(c["diff_ci90_low"]):+.3f}, {float(c["diff_ci90_high"]):+.3f}] & {v} \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write(f"{prefix}_scale.tex", t)

    t = [r"\begin{tabular}{@{}lrrrl@{}}", r"\toprule",
         r"Operation & archived, ms & this session, ms & ratio & TOST $\pm$10\% \\", r"\midrule"]
    for op in OPS:
        c = cmp.get(("seal_reproduction", op))
        if c:
            v = "equivalent" if c["verdict"] == "equivalent_within_margin" else "not established"
            t.append(f'{op} & {fmt(c["ref_mean_ms"])} & {fmt(c["new_mean_ms"])} & {float(c["ratio"]):.3f} & {v} \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write(f"{prefix}_reproduction.tex", t)

    for (kind, op), c in cmp.items():  # OpenFHE/SEAL ratios, e.g. \pilotRatioaddinplace
        if kind == "openfhe_vs_seal" and op in EQUIV:  # no ratio for end-to-end API costs
            macros[f"{prefix}Ratio{op.replace('_', '')}"] = f'{float(c["ratio"]):.2f}'
            macros[f"{prefix}Speedup{op.replace('_', '')}"] = f'{1 / float(c["ratio"]):.1f}'
    n_hv = sum(r["flag"] == "HIGH_VARIANCE" for r in lat.values())
    n_eq = sum(c["verdict"] == "equivalent_within_margin" for k, c in cmp.items() if k[0] == "scale_test")
    n_sc = sum(1 for k in cmp if k[0] == "scale_test")
    n_rep = sum(c["verdict"] == "equivalent_within_margin" for k, c in cmp.items() if k[0] == "seal_reproduction")
    n_rp = sum(1 for k in cmp if k[0] == "seal_reproduction")
    ok = sum(int(r["mean"]) for r in corr.values()); tot = sum(int(r["n"]) for r in corr.values())
    macros.update({f"{prefix}Cells": len(lat), f"{prefix}HighVar": n_hv, f"{prefix}ScaleEq": n_eq,
                   f"{prefix}ScaleN": n_sc, f"{prefix}ReproEq": n_rep, f"{prefix}ReproN": n_rp,
                   f"{prefix}CorrectOK": ok, f"{prefix}CorrectN": tot})
    temp = f"../results/raw/{run}/temperature_log.csv"
    if os.path.exists(temp):
        ts = [int(r["temp_millic"]) / 1000 for r in csv.DictReader(open(temp)) if r["temp_millic"]]
        ts.sort()
        macros.update({f"{prefix}TempMedian": f"{ts[len(ts) // 2]:.0f}", f"{prefix}TempMax": f"{ts[-1]:.0f}",
                       f"{prefix}TempHotShare": f"{100 * sum(x >= 90 for x in ts) / len(ts):.0f}"})


def static_tables(macros):
    # repeated correctness check (all eligible configurations)
    agg = defaultdict(lambda: [0, 0, 0.0, set(), ""])
    for r in csv.DictReader(open("correctness/correctness_v2.csv")):
        a = agg[(r["scheme"], int(r["N"]), int(r["category"]))]
        a[0] += int(r["trials"]); a[1] += int(r["passed"]); a[2] = max(a[2], float(r["worst"]))
        a[3].add(r["operation"]); a[4] = r["metric"]
    t = [r"\begin{tabular}{@{}llrrr@{}}", r"\toprule",
         r"Configuration & Operations checked & Checks passed & Worst error \\", r"\midrule"]
    for (s, N, c), (n, p, w, ops, m) in sorted(agg.items(), key=lambda k: (k[0][1], k[0][2], k[0][0])):
        worst = f"{w:.1e}" if m == "max_norm_error" else "exact"
        t.append(f"{s} {N}/{c} & {len(ops)} & {p}/{n} & {worst} \\\\")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("correctness.tex", t)
    tot_n = sum(a[0] for a in agg.values()); tot_p = sum(a[1] for a in agg.values())
    neg = list(csv.DictReader(open("correctness/negative_controls_out.csv")))
    neg_fail = sum(int(r["passed"]) == 0 for r in neg if r["operation"] in ("decrypt", "add", "multiply", "relinearize"))
    macros.update({"corrConfigs": len(agg), "corrPassed": tot_p, "corrTotal": tot_n,
                   "negFailed": neg_fail, "eligible": sum(1 for _ in csv.DictReader(open("probe/eligible_v2.csv"))),
                   "securityEvaluated": sum(1 for _ in csv.DictReader(open("probe/security_v2.csv")))})

    # cost-model sensitivity
    sens = {}
    for path in ("../security/results_sensitivity_N8192_cat5.csv", "../security/results_sensitivity_seal_N8192_cat5.csv"):
        for r in csv.DictReader(open(path)):
            if r["attack"] == "MIN":
                model = r["cost_model"].split(" ")[0]
                sens[(r["scheme"], model)] = (float(r["log2_rop"]), float(r["log2_qp"]))
    t = [r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
         r"Configuration ($N{=}8192$, cat.~5) & $\log_2 q$ & MATZOV (default) & BDGL16 & ADPS16 (core-SVP) \\", r"\midrule"]
    for s in ("BFV", "BGV", "CKKS", "SEAL"):
        name = "SEAL (BFV/BGV/CKKS)" if s == "SEAL" else f"OpenFHE {s}"
        vals = [sens[(s, m)][0] for m in ("MATZOV", "BDGL16", "ADPS16")]
        cells = [f"{v:.1f}" if v >= 256 else f"\\textbf{{{v:.1f}}}" for v in vals]
        t.append(f"{name} & {sens[(s, 'MATZOV')][1]:.0f} & " + " & ".join(cells) + r" \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("sensitivity.tex", t)


def validation_tables(path, macros):
    """Tables of the validation session (aggregate.py --scenario=validation)
    and the summaries of the two test logs. Formatting only."""
    v = list(csv.DictReader(open(path)))
    get = lambda item, metric: next((r for r in v if r["item"] == item and r["metric"] == metric), None)
    t = [r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
         r"Block (scale) & latency, ms [95\% CI] & CV\% & eff.\ frequency, MHz & temperature, \textdegree C \\",
         r"\midrule"]
    for b, sc in enumerate([40, 30, 30, 40, 40, 30, 30, 40], start=1):
        tag = f"seal_ckks_N8192_cat1_relinearize_scale{sc}_b{b}"
        lat, fr, te = get(tag, "latency_ms"), get(tag, "effective_freq_mhz_mean"), get(tag, "temp_c_mean")
        if not lat:
            t.append(f"{b} ($2^{{{sc}}}$) & \\multicolumn{{4}}{{c}}{{invalid -- excluded}} \\\\"); continue
        cv = 100 * float(lat["std"]) / float(lat["value"])
        t.append(f'{b} ($2^{{{sc}}}$) & {fmt(lat["value"])} [{fmt(lat["ci_low"])}, {fmt(lat["ci_high"])}] & {cv:.1f} & '
                 f'{float(fr["value"]):.0f} & {float(te["value"]):.1f} \\\\')
    bl = [get(f"seal_ckks_N8192_cat1_relinearize_scale{sc}_b{b}", "latency_ms") for b, sc in
          enumerate([40, 30, 30, 40, 40, 30, 30, 40], start=1)]
    bf = [get(f"seal_ckks_N8192_cat1_relinearize_scale{sc}_b{b}", "effective_freq_mhz_mean") for b, sc in
          enumerate([40, 30, 30, 40, 40, 30, 30, 40], start=1)]
    if all(bl) and all(bf):
        lv, fv = [float(x["value"]) for x in bl], [float(x["value"]) for x in bf]
        macros.update({"blockLatMin": fmt(min(lv)), "blockLatMax": fmt(max(lv)),
                       "blockLatSpread": f"{100 * (max(lv) - min(lv)) / min(lv):.1f}",
                       "blockFreqMin": f"{min(fv):.0f}", "blockFreqMax": f"{max(fv):.0f}",
                       "blockFreqSpread": f"{100 * (max(fv) - min(fv)) / min(fv):.1f}",
                       "freqShareOfMax": f"{100 * statistics.median(fv) / float(get('max boost frequency', 'mhz')['value']):.0f}"})
    t.append(r"\midrule")
    for sc in (40, 30):
        r = get(f"pooled scale 2^{sc}", "latency_ms")
        if r:
            cv = 100 * float(r["std"]) / float(r["value"])
            t.append(f'pooled $2^{{{sc}}}$ ({r["n"]} reps) & {fmt(r["value"])} [{fmt(r["ci_low"])}, {fmt(r["ci_high"])}] & {cv:.1f} & & \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    write("validation_relin.tex", t)
    ratio, tost, diff = get("scale 2^30 vs 2^40", "ratio"), get("scale 2^30 vs 2^40", "tost_5pct"), get("scale 2^30 vs 2^40", "diff_ms_ci90")
    if ratio:
        macros.update({"relinRatio": f'{float(ratio["value"]):.3f}',
                       "relinTost": "equivalent within $\\pm$5\\%" if tost["value"] == "equivalent_within_margin" else "equivalence not established",
                       "relinDiffLow": f'{100 * float(diff["ci_low"]) / float(get("pooled scale 2^40", "latency_ms")["value"]):+.1f}',
                       "relinDiffHigh": f'{100 * float(diff["ci_high"]) / float(get("pooled scale 2^40", "latency_ms")["value"]):+.1f}',
                       "relinCorrFreq": f'{float(get("blocks", "corr_latency_vs_effective_freq")["value"]):+.2f}',
                       "relinCorrPos": f'{float(get("blocks", "corr_latency_vs_position")["value"]):+.2f}'})
    for part in ("A", "B"):
        f, te, sh = get(f"part {part}", "effective_freq_mhz_median"), get(f"part {part}", "temp_c_median"), get(f"part {part}", "share_below_90pct_max_boost")
        if f:
            macros.update({f"freqMedian{part}": f'{float(f["value"]):.0f}', f"tempMedian{part}": f'{float(te["value"]):.0f}',
                           f"shareBelow{part}": f'{100 * float(sh["value"]):.0f}'})
    mx = get("max boost frequency", "mhz")
    if mx:
        macros["freqMaxBoost"] = f'{float(mx["value"]):.0f}'

    t = [r"\begin{tabular}{@{}llrrcrrc@{}}", r"\toprule",
         r"& & \multicolumn{3}{c}{net J/op (session idle baseline)} & gross & SEAL gross & memory, MB \\",
         r"Library & Operation & inv.\ 1 & inv.\ 2 & 2/1, TOST $\pm$10\% & 2/1 & vs archived & (vs archived) \\",
         r"\midrule"]
    ok = lambda r: r is not None and r["value"] != "" and not r["value"].startswith("NOT")
    for r in csv.DictReader(open("validation/energy_plan_ckks8192.csv")):
        lib, op = r["library"], r["operation"]
        item = f"{lib} {op}"
        e1 = get(f"{lib}_ckks_N8192_cat1_{op}_energy1", "energy_net_j_per_op")
        e2 = get(f"{lib}_ckks_N8192_cat1_{op}_energy2", "energy_net_j_per_op")
        rep, rept = get(item, "energy_repeatability_ratio_inv2_inv1"), get(item, "energy_repeatability_tost_10pct")
        grep_ = get(item, "gross_repeatability_ratio_inv2_inv1")
        garc = get(item, "gross_vs_archived_ratio")
        mem, marc = get(item, "peak_memory_mb"), get(item, "memory_vs_archived_ratio")
        f4 = lambda x: f'{float(x["value"]):.4f}' if ok(x) else "--"
        verdict = ("equiv." if rept and rept["value"] == "equivalent_within_margin" else "not est.") if rept else ""
        memtxt = (f'{float(mem["value"]):.1f}' if ok(mem) else "--") + (f' ({float(marc["value"]):.3f})' if ok(marc) else "")
        t.append(f'{"SEAL" if lib == "seal" else "OpenFHE"} & {op} & {f4(e1)} & {f4(e2)} & '
                 f'{float(rep["value"]):.3f}, {verdict} & {float(grep_["value"]):.3f} & '
                 f'{(format(float(garc["value"]), ".3f")) if ok(garc) else "--"} & {memtxt} \\\\')
    t += [r"\bottomrule", r"\end{tabular}"]
    sb, cb = get("idle baseline, this session (median of its readings)", "watts"), get("idle baseline, SEAL campaign (pooled median)", "watts")
    if sb and cb:
        macros.update({"idleSession": f'{float(sb["value"]):.1f}', "idleCampaign": f'{float(cb["value"]):.1f}'})
    plan_rows = list(csv.DictReader(open("validation/energy_plan_ckks8192.csv")))
    garcs = [float(get(f"seal {x['operation']}", "gross_vs_archived_ratio")["value"]) for x in plan_rows if x["library"] == "seal"]
    marcs = [float(get(f"seal {x['operation']}", "memory_vs_archived_ratio")["value"]) for x in plan_rows if x["library"] == "seal"]
    msds = [float(get(f"{x['library']} {x['operation']}", "peak_memory_mb")["std"]) for x in plan_rows]
    macros.update({"grossLowerMin": f"{100 * (1 - max(garcs)):.0f}", "grossLowerMax": f"{100 * (1 - min(garcs)):.0f}",
                   "memArchivedMaxDev": f"{100 * max(abs(1 - m) for m in marcs):.1f}",
                   "memStdMax": f"{max(msds):.2f}"})
    p40 = get("pooled scale 2^40", "latency_ms")
    pil = next((float(r["mean"]) for r in csv.DictReader(open("../results/final/pilot.csv"))
                if (r["library"], r["operation"], r["ckks_scale_bits"], r["metric"]) == ("SEAL", "relinearize", "40", "latency_ms")), None)
    arc = next((float(r["mean"]) for r in csv.DictReader(open("../results/final/seal_standard.csv"))
                if (r["scheme"], r["N"], r["category"], r["operation"], r["metric"]) == ("CKKS", "8192", "1", "relinearize", "latency_ms")), None)
    if p40 and pil and arc:
        macros.update({"relinHere": f'{float(p40["value"]):.2f}', "relinPilot": f"{pil:.2f}", "relinArchived": f"{arc:.2f}"})
    reps = [get(f"{x['library']} {x['operation']}", "energy_repeatability_tost_10pct") for x in csv.DictReader(open("validation/energy_plan_ckks8192.csv"))]
    macros["energyRepEq"] = sum(1 for x in reps if x and x["value"] == "equivalent_within_margin")
    macros["energyRepN"] = len(reps)
    write("validation_energy.tex", t)


def log_result(path):
    if not os.path.exists(path):
        return "not run"
    lines = [l for l in open(path) if l.startswith("RESULT:")]
    return lines[-1].split("RESULT:", 1)[1].strip() if lines else "incomplete"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="pilot")
    ap.add_argument("--prefix", default=None)
    ap.add_argument("--validation", default="../results/final/validation_v2.csv")
    a = ap.parse_args()
    prefix = a.prefix or a.run.replace("_", "")
    macros = {}
    static_tables(macros)
    results_tables(a.run, prefix, macros)
    if a.validation and os.path.exists(a.validation):
        vm = {"FailClosedSummary": log_result("validation/failclosed_tests.log"),
              "SelfTestSummary": log_result("validation/harness_selftest.log")}
        validation_tables(a.validation, vm)
        write("validation_numbers.tex", [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in vm.items()]
              + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items() if not k.startswith(prefix)])
    write(f"{prefix}_numbers.tex", [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()
                                    if k.startswith(prefix)])
    write("static_numbers.tex", [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()
                                 if not k.startswith(prefix)])
    print("wrote", sorted(os.listdir(OUT)))


if __name__ == "__main__":
    main()
