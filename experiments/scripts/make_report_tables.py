#!/usr/bin/env python3
"""Generate the report's data tables and figures directly from the final
CSVs, so no number in the report is ever typed in by hand.

Writes LaTeX fragments to report/generated/, which the report \\input{}s.
Re-run after any re-aggregation:  python3 make_report_tables.py
(from experiments/scripts/, like aggregate.py).

Formatting only -- no statistics are computed here (aggregate.py stays the
only place that happens); every value is read straight from a final CSV.
"""
import csv
import math
import os
from collections import defaultdict

FINAL = "../results/final"
OUT = "../../report/generated"

CELLS = [(n, c) for n in (2048, 4096, 8192) for c in (1, 3, 5)]
SCHEME_COLORS = {"BFV": "seaBlue", "BGV": "seaTeal"}


def load(name):
    with open(os.path.join(FINAL, name), newline="") as f:
        return list(csv.DictReader(f))


def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% GENERATED by experiments/scripts/make_report_tables.py"
                " -- do not edit by hand.\n" + text)
    print(f"wrote report/generated/{name}")


def sci(x):
    """1.5e-04 -> $1.5{\\times}10^{-4}$; values >= 0.01 printed plainly."""
    if x >= 0.01:
        return f"{x:.2g}" if x < 10 else f"{x:.0f}"
    m, e = f"{x:.1e}".split("e")
    return f"${m}{{\\times}}10^{{{int(e)}}}$"


def bits(x):
    return f"{x:.1f}".rstrip("0").rstrip(".")


# ---------------------------------------------------------------- noise budget
def noise_budget():
    rows = [r for r in load("seal_noise_budget.csv") if r["mean"]]
    nb = defaultdict(dict)  # (scheme, N, cat) -> step -> mean bits
    for r in rows:
        nb[(r["scheme"], int(r["N"]), int(r["category"]))][r["operation"]] = float(r["mean"])

    def last_mult(steps):
        ks = sorted(k for k in steps if k.startswith("after_relinearize_"))
        return (int(ks[-1].rsplit("_", 1)[1]), steps[ks[-1]]) if ks else (0, None)

    # Table: every cell, BFV and BGV side by side.
    lines = [r"\begin{tabular}{@{}cc ccc ccc@{}}", r"\toprule",
             r" & & \multicolumn{3}{c}{\textbf{BFV}} & \multicolumn{3}{c}{\textbf{BGV}} \\",
             r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
             r"$N$ & Cat. & Fresh & +add & After last mult. & Fresh & +add & After last mult. \\",
             r"\midrule"]
    for n, c in CELLS:
        cells = []
        for s in ("BFV", "BGV"):
            st = nb[(s, n, c)]
            k, v = last_mult(st)
            cells += [bits(st["fresh"]), bits(st["after_add"]),
                      f"{bits(v)} ({k}$\\times$)" if k else "--"]
        lines.append(f"{n} & {c} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("noise_budget_table.tex", "\n".join(lines) + "\n")

    # Figure: complete traces for the two cells that support multiplication
    # at N=8192, both schemes.
    order = ["fresh", "after_add"] + [f"after_{op}_{i}" for i in range(1, 4)
                                       for op in ("multiply", "relinearize")]
    plots = []
    styles = {(8192, 1): ("solid", "*"), (8192, 3): ("dashed", "square*")}
    legend = []
    for (n, c), (dash, mark) in styles.items():
        for s in ("BFV", "BGV"):
            st = nb[(s, n, c)]
            coords = " ".join(f"({i},{st[k]:g})" for i, k in enumerate(order) if k in st)
            plots.append(f"    \\addplot[very thick, {dash}, mark={mark}, mark size=1.3pt, "
                         f"{SCHEME_COLORS[s]}] coordinates {{{coords}}};")
            legend.append(f"{{{s}, $N{{=}}{n}$/cat.~{c}}}")
    fig = "\n".join([
        r"\begin{tikzpicture}",
        r"  \begin{axis}[",
        r"      width=12cm, height=5.4cm,",
        r"      xlabel={Step}, ylabel={Noise budget (bits)},",
        r"      xtick={0,...,7}, xticklabels={fresh,+add,mult 1,relin 1,mult 2,relin 2,mult 3,relin 3},",
        r"      x tick label style={font=\scriptsize, rotate=30, anchor=east},",
        r"      ymin=0, axis lines*=left, ymajorgrids, grid style={gray!20},",
        r"      legend style={font=\scriptsize, at={(0.98,0.98)}, anchor=north east},",
        r"    ]",
        *plots,
        "    \\legend{" + ", ".join(legend) + "}",
        r"  \end{axis}",
        r"\end{tikzpicture}"])
    write("noise_budget_figure.tex", fig + "\n")

    # Plaintext-modulus exception table (methodology): margin after add.
    pm = {(int(r["N"]), int(r["category"])): r["plain_modulus"]
          for r in load("seal_config_metadata.csv") if r["scheme"] == "BFV"}
    lines = [r"\begin{tabular}{@{}cccc@{}}", r"\toprule",
             r"$N$ & Category & Plaintext modulus $t$ & Budget after add (BFV / BGV) \\",
             r"\midrule"]
    for n, c in CELLS:
        t = int(pm[(n, c)])
        if t == 1032193:
            continue
        lines.append(f"{n} & {c} & {t} ({t.bit_length()}-bit) & "
                     f"{bits(nb[('BFV', n, c)]['after_add'])} / "
                     f"{bits(nb[('BGV', n, c)]['after_add'])} bits \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("plainmod_table.tex", "\n".join(lines) + "\n")


# ------------------------------------------------------------------ CKKS error
def ckks():
    err = defaultdict(dict)  # (N, cat) -> (step, metric) -> mean
    for r in load("seal_ckks_error.csv"):
        if r["scheme"] == "CKKS" and r["mean"]:
            err[(int(r["N"]), int(r["category"]))][(r["operation"], r["metric"])] = float(r["mean"])
    scale = {(int(r["N"]), int(r["category"])): round(math.log2(float(r["initial_scale"])))
             for r in load("seal_config_metadata.csv")
             if r["scheme"] == "CKKS" and r["initial_scale"]}

    def last_step(n, c):
        rs = sorted(s for s, m in err[(n, c)] if s.startswith("after_rescale_"))
        return rs[-1] if rs else "after_add"

    # Methodology table: scale + error for every CKKS cell.
    lines = [r"\begin{tabular}{@{}cccll@{}}", r"\toprule",
             r"$N$ & Cat. & Scale & Max / mean error after add & Max error, last step \\",
             r"\midrule"]
    for n, c in CELLS:
        e = err[(n, c)]
        ls = last_step(n, c)
        last = (f"{sci(e[(ls, 'max_abs_error')])} ({ls.replace('after_', '').replace('_', ' ')})"
                if ls != "after_add" else "--")
        lines.append(f"{n} & {c} & $2^{{{scale[(n, c)]}}}$ & "
                     f"{sci(e[('after_add', 'max_abs_error')])} / {sci(e[('after_add', 'mean_abs_error')])} & "
                     f"{last} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("ckks_table.tex", "\n".join(lines) + "\n")

    # Figure: max error after add, every cell, log scale.
    coords = " ".join(f"({n}/{c},{err[(n, c)][('after_add', 'max_abs_error')]:.3g})"
                      for n, c in CELLS)
    labels = ",".join(f"{n}/{c}" for n, c in CELLS)
    fig = "\n".join([
        r"\begin{tikzpicture}",
        r"  \begin{axis}[",
        r"      width=12cm, height=5cm, ybar, bar width=0.55cm,",
        f"      symbolic x coords={{{labels}}}, xtick=data,",
        r"      x tick label style={font=\scriptsize},",
        r"      xlabel={$N$/category}, ylabel={Max.\ abs.\ error after add},",
        r"      ymode=log, log origin=infty, axis lines*=left, ymin=1e-9, ymax=1,",
        r"      ytick={1e-8,1e-6,1e-4,1e-2,1},",
        r"      ymajorgrids, grid style={gray!20},",
        r"    ]",
        f"    \\addplot[fill=seaTeal!70] coordinates {{{coords}}};",
        r"  \end{axis}",
        r"\end{tikzpicture}"])
    write("ckks_error_figure.tex", fig + "\n")


# ------------------------------------------------------------------ composite
def composite():
    comp = load("seal_composite.csv")
    get = lambda s, op, m, vl="": next(float(r["mean"]) for r in comp if r["scheme"] == s
                                      and r["operation"] == op and r["metric"] == m
                                      and r["vec_len"] == vl)

    # Single-operation building blocks: rotation, Galois keys, poly_eval.
    lines = [r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
             r"Scheme & Rotate (ms) & Galois keygen (ms) & Galois key, 1 step (MB) & Poly.\ eval.\ (ms) \\",
             r"\midrule"]
    for s in ("BFV", "BGV", "CKKS"):
        lines.append(f"{s} & {get(s, 'rotate', 'latency_ms'):.2f} & "
                     f"{get(s, 'rotate', 'galois_keygen_ms'):.2f} & "
                     f"{get(s, 'rotate', 'galois_keys_size_bytes') / 1e6:.2f} & "
                     f"{get(s, 'poly_eval', 'latency_ms'):.2f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("composite_ops_table.tex", "\n".join(lines) + "\n")

    # Predicted vs measured dot product (TOST), plus end-of-chain budget.
    ctrl = defaultdict(dict)
    for r in load("seal_composite_controls.csv"):
        ctrl[(r["scheme"], r["operation"], int(r["vec_len"]))][r["step"]] = float(r["mean"])

    def ctrl_drop(s, op, vl):
        st = ctrl[(s, op, vl)]
        last = max((k for k in st if k != "fresh"), key=lambda k: int(k.rsplit("_", 1)[1]))
        return st["fresh"] - st[last]

    lines = [r"\begin{tabular}{@{}lrrrrrrlll@{}}", r"\toprule",
             r"Scheme & Length & $k$ & Pred.\ (ms) & Meas.\ (ms) & Diff. & W--S df & 90\% CI, W--S (ms) & 90\% CI, bootstrap (ms) & TOST \\",
             r"\midrule"]
    pred = load("seal_composite_prediction.csv")
    for r in pred:
        p_, a_ = float(r["predicted_ms"]), float(r["actual_ms"])
        both = r["ws_verdict"] == r["boot_verdict"] == "equivalent_within_margin"
        verdict = "equivalent" if both else "not established"
        lines.append(f"{r['scheme']} & {r['vec_len']} & {r['rotate_steps']} & {p_:.2f} & {a_:.2f} & "
                     f"{100 * (a_ - p_) / p_:+.1f}\\% & {float(r['ws_df']):.0f} & "
                     f"[{float(r['ws_ci_low']):+.2f}, {float(r['ws_ci_high']):+.2f}] & "
                     f"[{float(r['boot_ci_low']):+.2f}, {float(r['boot_ci_high']):+.2f}] & "
                     f"{verdict} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("composite_prediction_table.tex", "\n".join(lines) + "\n")

    lines = [r"\begin{tabular}{@{}lrrccc@{}}", r"\toprule",
             r"Scheme & Length & $k$ & Budget after dot product & Rotate-only cost & Add-only cost \\",
             r"\midrule"]
    for r in pred:
        s, vl = r["scheme"], int(r["vec_len"])
        if s == "CKKS":
            continue
        lines.append(f"{s} & {vl} & {r['rotate_steps']} & "
                     f"{bits(get(s, 'dot_product', 'noise_budget_bits', str(vl)))} bits & "
                     f"{bits(ctrl_drop(s, 'rotate_only', vl))} bits & "
                     f"{bits(ctrl_drop(s, 'add_only', vl))} bits \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("composite_noise_table.tex", "\n".join(lines) + "\n")


# ------------------------------------------------------------- energy/memory
OPS = ["keygen", "encrypt", "decrypt", "add", "multiply", "relinearize"]


def energy_memory():
    D = {}
    for sc in ("standard", "constrained"):
        for r in load(f"seal_{sc}.csv"):
            if r["mean"]:
                D[(sc, r["metric"], r["scheme"], int(r["N"]), int(r["category"]), r["operation"])] = float(r["mean"])

    def rng(sc, metric, op, scale=1.0, fmt=sci):
        v = [x for k, x in D.items() if k[0] == sc and k[1] == metric and k[5] == op]
        return f"{fmt(min(v) * scale)} -- {fmt(max(v) * scale)}"

    mib = lambda x: f"{x:.1f}"
    lines = [r"\begin{tabular}{@{}lccc@{}}", r"\toprule",
             r"Operation & Gross energy (J/op) & Net energy, estimate (J/op) & Peak process RSS (MiB) \\",
             r"\midrule"]
    for op in OPS:
        lines.append(f"{op} & {rng('standard', 'energy_pkg_j_per_op', op)} & "
                     f"{rng('standard', 'energy_net_j_per_op', op)} & "
                     f"{rng('standard', 'peak_memory_mb', op, fmt=mib)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("energy_memory_table.tex", "\n".join(lines) + "\n")

    # Standard vs Constrained on the common N<=8192 cells: ratio distribution.
    def ratios(metric):
        r = sorted(D[("constrained",) + k[1:]] / x for k, x in D.items()
                   if k[0] == "standard" and k[1] == metric and ("constrained",) + k[1:] in D)
        q = lambda p: r[int(p * (len(r) - 1))]
        return len(r), q(0.5), q(0.1), q(0.9)

    hv = {sc: sum(1 for r in load(f"seal_{sc}.csv") if r["metric"] == "latency_ms"
                  and r["flag"] == "HIGH_VARIANCE" and int(r["N"]) <= 8192) for sc in ("standard", "constrained")}
    meas = {sc: sum(1 for r in load(f"seal_{sc}.csv") if r["metric"] == "latency_ms"
                    and r["mean"] and int(r["N"]) <= 8192) for sc in ("standard", "constrained")}
    mx = {sc: max(x for k, x in D.items() if k[0] == sc and k[1] == "peak_memory_mb" and k[3] <= 8192)
          for sc in ("standard", "constrained")}
    lines = [r"\begin{tabular}{@{}lccc@{}}", r"\toprule",
             r"Metric & Constrained / Standard (median) & 10th--90th percentile & Cells \\",
             r"\midrule"]
    for label, metric in (("Latency", "latency_ms"), ("Peak process RSS", "peak_memory_mb"),
                          ("Gross energy per op", "energy_pkg_j_per_op"),
                          ("Net energy per op", "energy_net_j_per_op")):
        n, med, lo, hi = ratios(metric)
        lines.append(f"{label} & {med:.2f} & {lo:.2f} -- {hi:.2f} & {n} \\\\")
    lines += [r"\midrule",
              f"Max.\\ peak process RSS (MiB) & \\multicolumn{{3}}{{l}}{{Standard {mx['standard']:.1f}, "
              f"Constrained {mx['constrained']:.1f}}} \\\\",
              f"\\texttt{{HIGH\\_VARIANCE}} latency & \\multicolumn{{3}}{{l}}{{Standard {hv['standard']}/{meas['standard']}, "
              f"Constrained {hv['constrained']}/{meas['constrained']}}} \\\\",
              r"\bottomrule", r"\end{tabular}"]
    write("std_vs_constrained_table.tex", "\n".join(lines) + "\n")


