#!/usr/bin/env python3
"""LaTeX tables and numbers of the Lattigo latency pilot (the pilot note,
docs/comparability/lattigo_pilot_note.tex, and the thesis input them;
nothing is typed by hand). Computes no statistics: it formats aggregate.py's
outputs (--scenario=lattigo_pilot), the recorded parameters (probe/) and the
session's records.

Usage (from experiments/lattigo/):  python3 make_lattigo_pilot_tables.py
Inputs:  ../results/final/lattigo_pilot{,_comparisons}.csv, probe/lattigo_params.csv,
         probe/probe_results.csv, ../results/raw/lattigo_pilot/{cell_times.csv,cpu_state.txt}
Outputs: pilot_tables/{latency,exact,numbers}.tex
"""
import csv
import os
import re

OUT = "pilot_tables"
FINAL = "../results/final/lattigo_pilot"
RAW = "../results/raw/lattigo_pilot"
OPS = [("keygen", "key generation"), ("encrypt", "encryption"), ("decrypt", "decryption"),
       ("decrypt_full", "decryption with decoding"), ("add", "addition"), ("multiply", "multiplication"),
       ("relinearize", "relinearization"), ("rotate", "rotation by one slot")]
SCHEMES = ("BFV", "BGV", "CKKS")


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% GENERATED by experiments/lattigo/make_lattigo_pilot_tables.py -- do not edit by hand.\n")
        fh.write("\n".join(lines) + "\n")


def ms(x):
    v = float(x)
    return f"{v:.0f}" if v >= 100 else f"{v:#.3g}".rstrip(".")


def main():
    m = {}
    res = list(csv.DictReader(open(FINAL + ".csv")))
    lat = {(r["library"], r["scheme"], r["operation"]): r for r in res if r["metric"] == "latency_ms"}
    prec = {(r["library"], r["operation"]): float(r["mean"]) for r in res if r["metric"] == "ckks_precision_bits_min"}
    corr = [r for r in res if r["metric"] == "correct_repetitions"]
    comps = list(csv.DictReader(open(FINAL + "_comparisons.csv")))
    exact = {(c["scheme"], c["operation"]): c for c in comps if c["comparison"] == "lattigo_vs_seal_exact"}

    # ---- latency table: Lattigo and SEAL per scheme; exact-parameter ratio where formed
    t = [r"\begin{tabular}{@{}l" + "rrr" * 3 + r"@{}}", r"\toprule",
         " & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{{s}}}" for s in SCHEMES) + r" \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
         "Operation" + r" & Lattigo & SEAL & ratio" * 3 + r" \\", r"\midrule"]
    for op, name in OPS:
        cells = []
        for s in SCHEMES:
            lv, sv = lat.get(("Lattigo", s, op)), lat.get(("SEAL", s, op))
            e = exact.get((s, op))
            cells += [ms(lv["mean"]) if lv else "--", ms(sv["mean"]) if sv else "--",
                      f"{float(e['ratio']):.2f}" if e else ""]
        t.append(f"{name} & " + " & ".join(cells) + r" \\")
    t.append(r"\midrule")
    pr = lambda lib: (f"{min(v for (l, _), v in prec.items() if l == lib):.1f}--"
                      f"{max(v for (l, _), v in prec.items() if l == lib):.1f}")
    t.append(rf"CKKS precision (bits) & \multicolumn{{6}}{{l}}{{}} & {pr('Lattigo')} & {pr('SEAL')} & \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("latency.tex", t)

    # ---- numbers
    m["ltCells"] = str(len(lat))
    m["ltLattigoCells"] = str(sum(1 for k in lat if k[0] == "Lattigo"))
    m["ltSealCells"] = str(sum(1 for k in lat if k[0] == "SEAL"))
    m["ltAllChecks"] = str(sum(int(r["n"]) for r in corr))
    m["ltLattigoChecks"] = str(sum(int(r["n"]) for r in corr if r["library"] == "Lattigo"))
    m["ltAllCorrect"] = "yes" if all(r["flag"] == "" for r in corr) else "NO"
    p = next(csv.DictReader(open("probe/lattigo_params.csv")))
    m["ltChain"], m["ltLogQ"] = p["seal_chain_bits"], p["seal_log2_q"]
    m["ltPlainMod"] = next(r for r in csv.DictReader(open("probe/lattigo_params.csv")) if r["scheme"] == "BGV")["plaintext_modulus"]
    probe = {r["scheme"]: r for r in csv.DictReader(open("probe/probe_results.csv"))}
    m["ltLogQP"] = probe["CKKS"]["log2QP"]
    m["ltSigma"] = re.search(r"\{([\d.]+) ", probe["CKKS"]["xe"]).group(1)
    for s in SCHEMES:
        lv = probe[s]["levels"]
        m[f"ltDepth{s.capitalize()}"] = str(sum(",OK" in part for part in lv.split("|")[1:]))
    m["ltPrecLatMin"], m["ltPrecLatMax"] = pr("Lattigo").split("--")
    m["ltPrecSealMin"], m["ltPrecSealMax"] = pr("SEAL").split("--")
    m["ltExactN"] = str(len(exact))
    r_of = lambda s, op: float(exact[(s, op)]["ratio"])
    m["ltRatioDecCkks"] = f"{r_of('CKKS', 'decrypt'):.2f}"
    mul = [r_of(s, "multiply") for s in ("CKKS", "BGV")]
    m["ltRatioMulMin"], m["ltRatioMulMax"] = f"{min(mul):.2f}", f"{max(mul):.2f}"
    ks = [r_of(s, op) for s in SCHEMES for op in ("relinearize", "rotate")]
    m["ltRatioKsMin"], m["ltRatioKsMax"] = f"{min(ks):.2f}", f"{max(ks):.2f}"
    ck = [r_of("CKKS", op) for op in ("relinearize", "rotate")]
    m["ltRatioKsCkksMin"], m["ltRatioKsCkksMax"] = f"{min(ck):.2f}", f"{max(ck):.2f}"
    bg = [r_of("BGV", op) for op in ("relinearize", "rotate")]
    m["ltRatioKsBgvMin"], m["ltRatioKsBgvMax"] = f"{min(bg):.2f}", f"{max(bg):.2f}"
    for (lib, s, op), r in lat.items():
        m[f"ltLat{lib}{s.capitalize()}{''.join(w.capitalize() for w in op.split('_'))}"] = ms(r["mean"])
    rep = [c for c in comps if c["comparison"] == "seal_reproduction"]
    m["ltReproN"] = str(len(rep))
    m["ltReproEq"] = str(sum(c["verdict"] == "equivalent_within_margin" for c in rep))
    m["ltReproOut"] = ", ".join(f"{c['scheme']} {c['operation']} ({float(c['ratio']):.2f})"
                                for c in rep if c["verdict"] != "equivalent_within_margin")
    # SEAL CKKS relinearize, this session and the HElib pilot, against the archived campaign
    m["ltReproCkksRelin"] = f"{float(next(c for c in rep if c['scheme'] == 'CKKS' and c['operation'] == 'relinearize')['ratio']):.2f}"
    hrep = [c for c in csv.DictReader(open("../results/final/helib_pilot_comparisons.csv"))
            if c["comparison"] == "seal_reproduction" and c["scheme"] == "CKKS" and c["operation"] == "relinearize"]
    m["ltReproCkksRelinHelib"] = f"{float(hrep[0]['ratio']):.2f}"
    # size of the ciphertext SEAL copies (2 polynomials x ciphertext primes x N x 8 bytes)
    nq = len(p["q_primes"].split())
    m["ltCopyMB"] = f"{2 * nq * int(p['N']) * 8 / 1e6:.1f}"
    times = list(csv.DictReader(open(RAW + "/cell_times.csv")))
    m["ltStart"], m["ltEnd"] = min(r["start"] for r in times)[11:16], max(r["end"] for r in times)[11:16]
    m["ltDate"] = min(r["start"] for r in times)[:10]
    state = open(RAW + "/cpu_state.txt").read()
    m["ltCommit"] = re.search(r"code commit: (\w{7})", state).group(1)
    m["ltGovernor"] = "performance" if "enforced performance: yes" in state else "NOT ENFORCED"
    m["ltBoost"] = "on" if "boost: 1" in state else "off"
    m["ltInner"] = re.search(r"inner_loop: (\d+)", state).group(1)
    reps = re.search(r"reps: (\d+) warmup: (\d+)", state)
    m["ltReps"], m["ltWarm"] = reps.group(1), reps.group(2)
    write("numbers.tex", [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())])
    print(f"wrote {OUT}/: latency, numbers ({len(m)} macros)")


if __name__ == "__main__":
    main()
