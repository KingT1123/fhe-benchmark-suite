#!/usr/bin/env python3
"""LaTeX tables and numbers of the HElib latency pilot (the pilot note,
docs/comparability/helib_pilot_note.tex, and the thesis input them; nothing
is typed by hand). Computes no statistics: it formats aggregate.py's outputs
(--scenario=helib_pilot), the recorded HElib parameters (probe/) and the
session's records.

Usage (from experiments/helib/):  python3 make_helib_pilot_tables.py
Inputs:  ../results/final/helib_pilot{,_comparisons}.csv, probe/helib_params.csv,
         probe/probe_results.csv, ../config/param_grid.csv,
         ../results/raw/helib_pilot/{cell_times.csv,cpu_state.txt,helib.log}
Outputs: pilot_tables/{params,latency,numbers}.tex
"""
import csv
import os
import re

OUT = "pilot_tables"
FINAL = "../results/final/helib_pilot"
RAW = "../results/raw/helib_pilot"
OPS = [("keygen", "keygen", "key generation"), ("encrypt", "encrypt", "encryption"),
       ("decrypt", "decrypt", "decryption (to polynomial)"), ("decrypt_full", None, "decryption with decoding"),
       ("add_inplace", "add", "addition$^\\ast$"), ("multiply", "multiply", "multiplication"),
       ("relinearize", "relinearize", "relinearization"), ("rotate", "rotate", "rotation by one slot")]
WORD = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% GENERATED by experiments/helib/make_helib_pilot_tables.py -- do not edit by hand.\n")
        fh.write("\n".join(lines) + "\n")


def ms(x):
    v = float(x)
    return f"{v:.0f}" if v >= 100 else f"{v:#.3g}".rstrip(".")


def main():
    m = {}
    res = list(csv.DictReader(open(FINAL + ".csv")))
    lat = {(r["library"], r["scheme"], r["operation"]): r for r in res if r["metric"] == "latency_ms"}
    prec = {(r["library"], r["operation"]): float(r["mean"]) for r in res if r["metric"] == "ckks_precision_bits_min"}
    corr = [r for r in res if r["metric"] == "correct_repetitions"]
    params = {r["scheme"]: r for r in csv.DictReader(open("probe/helib_params.csv"))}
    grid = next(r for r in csv.DictReader(open("../config/param_grid.csv")) if r["N"] == "8192" and r["category"] == "1")

    # ---- parameters table
    chain = grid["chain"].split("+")
    seal_q, seal_p = "+".join(chain[:-1]), chain[-1]
    t = [r"\begin{tabular}{@{}lllrrrl@{}}", r"\toprule",
         r"Library, scheme & $Q$ (bits) & $P$ (bits) & $\log_2 QP$ & Bound & Security & Depth \\", r"\midrule",
         f"SEAL, CKKS and BGV & {seal_q} & {seal_p} & {grid['logq_used']} & {params['CKKS']['he_standard_log2QP_max']} & 128 (HE standard) & {grid['depth']} \\\\"]
    for s in ("CKKS", "BGV"):
        p = params[s]
        t.append(f"HElib, {s} & {p['ctxt_bits']} & {p['special_bits']} & {float(p['log2QP']):.1f} & "
                 f"{p['he_standard_log2QP_max']} & {float(p['helib_security']):.0f} (HElib estimate) & {p['depth_reached']} \\\\")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("params.tex", t)

    # ---- latency table
    t = [r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
         r" & \multicolumn{2}{c}{CKKS} & \multicolumn{2}{c}{BGV} \\",
         r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
         r"Operation & HElib & SEAL & HElib & SEAL \\", r"\midrule"]
    for hop, sop, name in OPS:
        cells = []
        for s in ("CKKS", "BGV"):
            h = lat.get(("HElib", s, hop))
            q = lat.get(("SEAL", s, sop)) if sop else None
            cells += [ms(h["mean"]) if h else "--", ms(q["mean"]) if q else "--"]
        t.append(f"{name} & " + " & ".join(cells) + r" \\")
    t.append(r"\midrule")
    pr = lambda lib: (f"{min(v for (l, _), v in prec.items() if l == lib):.1f}--"
                      f"{max(v for (l, _), v in prec.items() if l == lib):.1f}")
    t.append(f"CKKS precision (bits) & {pr('HElib')} & {pr('SEAL')} & & \\\\")
    t += [r"\bottomrule", r"\end{tabular}"]
    write("latency.tex", t)

    # ---- numbers
    m["hlCells"] = str(len(lat))
    m["hlHelibCells"] = str(sum(1 for k in lat if k[0] == "HElib"))
    m["hlSealCells"] = str(sum(1 for k in lat if k[0] == "SEAL"))
    m["hlHelibChecks"] = str(sum(int(r["n"]) for r in corr if r["library"] == "HElib"))
    m["hlAllChecks"] = str(sum(int(r["n"]) for r in corr))
    m["hlAllCorrect"] = "yes" if all(r["flag"] == "" for r in corr) else "NO"
    for s in ("CKKS", "BGV"):
        p = params[s]
        k = s.capitalize()
        m[f"hl{k}Bits"], m[f"hl{k}C"] = p["bits"], p["c"]
        m[f"hl{k}Q"], m[f"hl{k}P"] = p["ctxt_bits"], p["special_bits"]
        m[f"hl{k}QP"], m[f"hl{k}Sec"] = f"{float(p['log2QP']):.1f}", f"{float(p['helib_security']):.0f}"
        m[f"hl{k}Depth"] = p["depth_reached"]
        m[f"hl{k}SmallN"] = str(len(p["small_primes"].split()))
    m["hlBgvPlainMod"] = params["BGV"]["param"]
    m["hlSealQ"], m["hlSealPbits"] = seal_q, seal_p
    m["hlCkksPrecParam"] = params["CKKS"]["param"]
    m["hlSealQP"], m["hlSealChain"] = grid["logq_used"], grid["chain"]
    m["hlPrecHelibMin"], m["hlPrecHelibMax"] = pr("HElib").split("--")
    m["hlPrecSealMin"], m["hlPrecSealMax"] = pr("SEAL").split("--")
    # probe: CKKS precision vs depth with the chosen primes
    probe = [r for r in csv.DictReader(open("probe/probe_results.csv")) if r["scheme"] == "CKKS"
             and r["bits_req"] == params["CKKS"]["bits"] and r["c"] == params["CKKS"]["c"]]
    hi = [r for r in probe if int(r["param"]) > int(params["CKKS"]["param"])]
    m["hlProbeHighPrecMax"] = max(r["param"] for r in hi)
    m["hlProbeHighPrecDepth"] = "/".join(sorted({r["depth_ok"] for r in hi}))
    bgv2 = [r for r in csv.DictReader(open("probe/probe_results.csv")) if r["scheme"] == "BGV"
            and len(r["ctxt_primes"].split()) == 2 and r["c"] == "2"]
    m["hlBgvTwoPrimesDepth"] = "/".join(sorted({r["depth_ok"] for r in bgv2}))
    m["hlProbeCandidates"] = str(sum(1 for r in csv.DictReader(open("probe/probe_results.csv")) if r["scheme"] in ("CKKS", "BGV")))
    # latency values quoted in the text
    for (lib, s, op), r in lat.items():
        key = f"hlLat{lib}{s.capitalize()}{''.join(w.capitalize() for w in op.split('_'))}"
        m[key] = ms(r["mean"])
    # SEAL reproduction
    comps = list(csv.DictReader(open(FINAL + "_comparisons.csv")))
    rep = [c for c in comps if c["comparison"] == "seal_reproduction"]
    eq = [c for c in rep if c["verdict"] == "equivalent_within_margin"]
    m["hlReproN"], m["hlReproEq"] = str(len(rep)), str(len(eq))
    m["hlReproOut"] = ", ".join(f"{c['scheme']} {c['operation']} ({float(c['ratio']):.2f})"
                                for c in rep if c["verdict"] != "equivalent_within_margin")
    # session
    times = list(csv.DictReader(open(RAW + "/cell_times.csv")))
    m["hlStart"], m["hlEnd"] = min(r["start"] for r in times)[11:16], max(r["end"] for r in times)[11:16]
    m["hlDate"] = min(r["start"] for r in times)[:10]
    state = open(RAW + "/cpu_state.txt").read()
    m["hlCommit"] = re.search(r"code commit: (\w{7})", state).group(1)
    m["hlGovernor"] = "performance" if "enforced performance: yes" in state else "NOT ENFORCED"
    m["hlBoost"] = "on" if "boost: 1" in state else "off"
    m["hlInner"] = re.search(r"inner_loop: (\d+)", state).group(1)
    reps = re.search(r"reps: (\d+) warmup: (\d+)", state)
    m["hlReps"], m["hlWarm"] = reps.group(1), reps.group(2)
    log = open(RAW + "/helib.log").read().splitlines()
    m["hlLogKs"] = str(sum("KS-noise-ratio" in l for l in log))
    m["hlLogTarget"] = str(sum("non-optimal targetSize" in l for l in log))
    m["hlLogOther"] = str(sum("KS-noise-ratio" not in l and "non-optimal targetSize" not in l for l in log))
    write("numbers.tex", [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())])
    print(f"wrote {OUT}/: params, latency, numbers ({len(m)} macros)")


if __name__ == "__main__":
    main()
